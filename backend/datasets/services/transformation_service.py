"""
Use cases for find-and-replace transformations.

The flow is two-step so users can inspect what will change before committing:
1. `preview` (hand-written pattern) or `preview_from_instruction` (pattern generated by
   the LLM from a natural-language description) runs the pattern over the current
   version and records a `Transformation` with statistics and sample changes, without
   modifying any data.
2. `apply` re-runs exactly that transformation and stores the result as a new version.
"""

import logging
from dataclasses import dataclass, replace

import pandas as pd
from django.conf import settings
from django.db import transaction
from django.utils import timezone

from datasets.exceptions import (
    InvalidRegex,
    InvalidReplacement,
    NoTargetColumns,
    PatternGenerationFailed,
    PatternMatchesEmpty,
    RegexTimeout,
    TransformationConflict,
    UnknownColumns,
)
from datasets.models import Dataset, Transformation
from datasets.services import dataset_service, file_io, llm, regex_engine

logger = logging.getLogger(__name__)


@dataclass(frozen=True)
class Preview:
    transformation: Transformation
    samples: list[regex_engine.CellChange]


# Errors caused by an unusable pattern. When the pattern came from the LLM these are fed
# back to it so it can correct itself; for hand-written patterns they go to the user.
PATTERN_ERRORS = (InvalidRegex, PatternMatchesEmpty, InvalidReplacement, RegexTimeout)


def preview(
    dataset: Dataset,
    *,
    pattern: str,
    replacement: str,
    flags: list[str],
    columns: list[str] | None = None,
    instruction: str = "",
) -> Preview:
    """Preview a hand-written pattern."""
    version = dataset.current_version
    df = file_io.read_dataframe(version.data_file.name)
    target_columns, result = _run(df, version.columns, pattern, flags, replacement, columns)
    return _record_preview(
        dataset,
        result,
        instruction=instruction,
        pattern=pattern,
        flags=flags,
        replacement=replacement,
        columns=target_columns,
    )


def preview_from_instruction(
    dataset: Dataset,
    *,
    instruction: str,
    replacement: str | None = None,
    columns: list[str] | None = None,
) -> Preview:
    """Ask the LLM for a pattern matching `instruction`, then preview it."""
    version = dataset.current_version
    df = file_io.read_dataframe(version.data_file.name)
    generated = generate_pattern(
        df,
        version.columns,
        instruction=instruction,
        replacement=replacement,
        columns=columns,
        generator=llm.get_regex_generator(),
    )
    return _record_preview(
        dataset,
        generated.result,
        instruction=instruction,
        explanation=generated.suggestion.explanation,
        pattern=generated.suggestion.pattern,
        flags=generated.suggestion.flags,
        replacement=generated.replacement,
        columns=generated.columns,
    )


@dataclass(frozen=True)
class GeneratedPattern:
    suggestion: llm.RegexSuggestion
    replacement: str
    columns: list[str]
    result: regex_engine.ReplaceResult
    attempts: int


def generate_pattern(
    df: pd.DataFrame,
    column_kinds: list[dict],
    *,
    instruction: str,
    replacement: str | None,
    columns: list[str] | None,
    generator: llm.RegexGenerator,
) -> GeneratedPattern:
    """Get a pattern from the LLM and run it over `df`, retrying with feedback if needed.

    Values the user set explicitly (replacement, columns) take precedence over what the
    LLM inferred from the instruction. If the suggested pattern is unusable or matches
    nothing, the problem is sent back to the LLM for another attempt.
    """
    request = llm.RegexRequest(instruction=instruction, columns=_column_context(df, column_kinds))
    known_columns = {column["name"] for column in column_kinds}
    max_attempts = settings.LLM_MAX_ATTEMPTS

    for attempt in range(1, max_attempts + 1):
        suggestion = generator.suggest(request)
        final_replacement = replacement if replacement is not None else suggestion.replacement
        final_replacement = final_replacement or ""
        # Ignore column names the LLM made up; fall back to the default (text columns).
        final_columns = columns or [c for c in suggestion.columns if c in known_columns] or None

        try:
            target_columns, result = _run(
                df,
                column_kinds,
                suggestion.pattern,
                suggestion.flags,
                final_replacement,
                final_columns,
            )
        except PATTERN_ERRORS as exc:
            problem = exc.message
        else:
            # A result that changes nothing may be legitimate, but more often means a wrong
            # guess about the data format or the request, so retry while attempts remain.
            if result.stats["total_cells_changed"] > 0 or attempt == max_attempts:
                return GeneratedPattern(
                    suggestion=suggestion,
                    replacement=final_replacement,
                    columns=target_columns,
                    result=result,
                    attempts=attempt,
                )
            if result.stats["total_matches"] == 0:
                problem = (
                    "The pattern matched nothing in the selected columns. Compare it with "
                    "the sample values and adjust it to the formats actually present in the "
                    "data."
                )
            else:
                problem = (
                    f"The pattern matched {result.stats['total_matches']} time(s), but the "
                    "replacement produces exactly the same text, so nothing would change. "
                    "Re-read the request and reconsider what the user wants the matches "
                    "replaced with."
                )

        logger.info("LLM attempt %d/%d rejected: %s", attempt, max_attempts, problem)
        request = replace(request, previous=suggestion, feedback=problem)

    raise PatternGenerationFailed(
        details={"pattern": suggestion.pattern, "reason": problem, "attempts": max_attempts}
    )


def _run(df, column_kinds, pattern, flags, replacement, columns):
    target_columns = _resolve_columns(column_kinds, columns)
    compiled = regex_engine.compile_pattern(pattern, flags)
    result = regex_engine.replace_in_columns(
        df,
        compiled,
        replacement,
        target_columns,
        timeout_seconds=settings.REGEX_TIMEOUT_SECONDS,
        sample_size=settings.PREVIEW_SAMPLE_SIZE,
    )
    return target_columns, result


def _record_preview(dataset, result, **fields) -> Preview:
    transformation = Transformation.objects.create(
        dataset=dataset,
        source_version=dataset.current_version,
        stats=result.stats,
        **fields,
    )
    return Preview(transformation=transformation, samples=result.samples)


def _column_context(df, column_kinds) -> list[llm.ColumnContext]:
    """Column names, kinds and a few distinct example values to ground the LLM."""
    context = []
    for column in column_kinds:
        values = df[column["name"]].dropna().drop_duplicates().head(settings.LLM_SAMPLE_VALUES)
        context.append(
            llm.ColumnContext(
                name=column["name"],
                kind=column["kind"],
                samples=[value[:100] for value in values],
            )
        )
    return context


def apply(transformation: Transformation) -> Transformation:
    with transaction.atomic():
        # Lock the dataset so two concurrent applies cannot both build on the same version.
        dataset = Dataset.objects.select_for_update().get(pk=transformation.dataset_id)
        transformation.refresh_from_db()

        if transformation.status == Transformation.Status.APPLIED:
            raise TransformationConflict(
                "ALREADY_APPLIED", "This transformation has already been applied."
            )
        if dataset.current_version_id != transformation.source_version_id:
            raise TransformationConflict(
                "STALE_VERSION",
                "The data has changed since this preview was made. Preview again.",
            )

        source = transformation.source_version
        compiled = regex_engine.compile_pattern(transformation.pattern, transformation.flags)
        result = regex_engine.replace_in_columns(
            file_io.read_dataframe(source.data_file.name),
            compiled,
            transformation.replacement,
            transformation.columns,
            timeout_seconds=settings.REGEX_TIMEOUT_SECONDS,
            sample_size=0,
        )

        transformation.result_version = dataset_service.add_version(
            dataset, result.data, parent=source
        )
        transformation.status = Transformation.Status.APPLIED
        transformation.stats = result.stats
        transformation.applied_at = timezone.now()
        transformation.save()

    logger.info(
        "Applied transformation %s to dataset %s -> v%d",
        transformation.id,
        dataset.id,
        transformation.result_version.version_no,
    )
    return transformation


def _resolve_columns(available: list[dict], requested: list[str] | None) -> list[str]:
    """Validate requested columns; default to every text column."""
    names = [column["name"] for column in available]
    if requested:
        unknown = [name for name in requested if name not in names]
        if unknown:
            raise UnknownColumns(
                details={"unknown": unknown, "available": names},
            )
        return list(dict.fromkeys(requested))  # de-duplicate, keep order

    text_columns = [column["name"] for column in available if column["kind"] == "text"]
    if not text_columns:
        raise NoTargetColumns(details={"available": names})
    return text_columns
